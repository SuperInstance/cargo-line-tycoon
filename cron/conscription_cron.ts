/**
 * conscription_cron.ts — The cron that turns student observations into shipped code patches.
 *
 * Reads witness-logs from a Quilt cell-graph JSON dump, tallies feature_request observations,
 * and ships patches for features with consensus ≥ 5%.
 *
 * Usage: 
 *   npx tsx /workspace/research/cargo-line-tycoon/cron/conscription_cron.ts <witness_log.json>
 *   npx tsx /workspace/research/cargo-line-tycoon/cron/conscription_cron.ts --test
 */

import * as fs from 'fs';
import * as path from 'path';

interface WitnessEntry {
  op: string;
  source: string;
  payload: any;
  timestamp: number;
}

interface StudentSignal {
  source: string;
  target: string;
  signal_type: string;
  payload: any;
  timestamp: number;
}

interface PatchDecision {
  feature: string;
  consensus_pct: number;
  supporters: string[];
  patch_path: string;
  shipped_at: number;
}

interface RunLog {
  timestamp: number;
  witness_log_file: string;
  n_students: number;
  n_observations: number;
  n_features_requested: number;
  top_features: Array<{ feature: string; votes: number; pct: number }>;
  patches_shipped: PatchDecision[];
  consensus_threshold: number;
  total_features_in_canon: number;
}

const CONSENSUS_THRESHOLD = 0.05;  // 5%

function loadWitnessLog(file: string): { students: Set<string>; signals: StudentSignal[] } {
  const raw = JSON.parse(fs.readFileSync(file, 'utf-8'));
  const signals = raw.signals || [];
  const students = new Set<string>();
  for (const sig of signals) {
    if (sig.signal_type === 'feature_request' && sig.payload?.requested_by) {
      students.add(sig.payload.requested_by);
    }
  }
  return { students, signals };
}

function tallyFeatureRequests(signals: StudentSignal[]): Map<string, string[]> {
  const tallies = new Map<string, string[]>();
  for (const sig of signals) {
    if (sig.signal_type === 'feature_request' && sig.payload?.feature) {
      const feature = sig.payload.feature;
      const requester = sig.payload.requested_by || sig.source;
      if (!tallies.has(feature)) tallies.set(feature, []);
      const supporters = tallies.get(feature)!;
      if (!supporters.includes(requester)) {
        supporters.push(requester);
      }
    }
  }
  return tallies;
}

function generatePatch(feature: string, supporter_count: number): string {
  const featureSafe = feature.replace(/[^a-z0-9_]/g, '_');
  const patchPath = path.join('/tmp', `patch_${featureSafe}.ts`);
  
  const patchContent = `// AUTO-GENERATED by conscription_cron.ts
// Feature: ${feature}
// Shipped at: ${new Date().toISOString()}
// Supporters: ${supporter_count}

export const feature_${featureSafe} = {
  name: '${feature}',
  shipped_at: Date.now(),
  shipped_by: 'conscription_cron',
  supporter_count: ${supporter_count},
  metadata: {
    auto_generated: true,
    feature_id: '${featureSafe}',
    source: 'witness-log quorum',
  },
};

export function activate_${featureSafe}() {
  return feature_${featureSafe};
}
`;

  fs.writeFileSync(patchPath, patchContent);
  return patchPath;
}

function runConscriptionCron(witnessLogFile: string): RunLog {
  console.log('╔════════════════════════════════════════════════════════════════╗');
  console.log('║  Conscription Cron — witness-log → code patches                ║');
  console.log('╚════════════════════════════════════════════════════════════════╝');
  console.log(`Witness log: ${witnessLogFile}`);
  console.log(`Consensus threshold: ${CONSENSUS_THRESHOLD * 100}%\n`);

  // 1. Load witness log
  const { students, signals } = loadWitnessLog(witnessLogFile);
  const n_students = students.size;
  const n_observations = signals.length;
  console.log(`Students: ${n_students}`);
  console.log(`Observations: ${n_observations}`);

  // 2. Tally feature requests
  const tallies = tallyFeatureRequests(signals);
  const features_requested = tallies.size;
  console.log(`Distinct features: ${features_requested}\n`);

  // 3. Sort by votes
  const ranked = Array.from(tallies.entries())
    .map(([feature, supporters]) => ({
      feature,
      votes: supporters.length,
      pct: supporters.length / Math.max(n_students, 1),
    }))
    .sort((a, b) => b.votes - a.votes);

  console.log('Top features by vote:');
  for (const r of ranked.slice(0, 10)) {
    const verdict = r.pct >= CONSENSUS_THRESHOLD ? '✓ PROMOTE' : '○ review';
    console.log(`  ${verdict}  ${r.feature.padEnd(28)} ${r.votes} votes (${(r.pct * 100).toFixed(1)}%)`);
  }
  console.log('');

  // 4. Ship patches for promoted features
  const patches: PatchDecision[] = [];
  const promoted = ranked.filter(r => r.pct >= CONSENSUS_THRESHOLD);
  
  for (const p of promoted) {
    const supporters = tallies.get(p.feature) || [];
    const patchPath = generatePatch(p.feature, supporters.length);
    patches.push({
      feature: p.feature,
      consensus_pct: p.pct,
      supporters,
      patch_path: patchPath,
      shipped_at: Date.now(),
    });
    console.log(`  → shipped: ${p.feature} (${patchPath})`);
  }

  // 5. Build run log
  const runLog: RunLog = {
    timestamp: Date.now(),
    witness_log_file: witnessLogFile,
    n_students,
    n_observations,
    n_features_requested: features_requested,
    top_features: ranked.slice(0, 20),
    patches_shipped: patches,
    consensus_threshold: CONSENSUS_THRESHOLD,
    total_features_in_canon: 0, // computed in JS port
  };
  
  console.log(`\nShipped: ${patches.length} patches`);
  return runLog;
}

