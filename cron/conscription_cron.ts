function generateTestWitnessLog(students: number, features: number, density: number = 0.3): string {
  const FEATURES = [
    'weather_routing', 'fuel_estimator', 'crew_schedule', 'cargo_tier_picker',
    'speed_optimization', 'route_alternatives', 'piracy_zone_map', 'currency_converter',
    'time_zone_display', 'language_selector', 'sound_effects', 'background_music',
  ];
  const signals: StudentSignal[] = [];
  for (let i = 0; i < students; i++) {
    // Each student requests 1-3 features
    const nFeatures = 1 + Math.floor(Math.random() * 3);
    for (let j = 0; j < nFeatures; j++) {
      const f = FEATURES[Math.floor(Math.random() * Math.min(features, FEATURES.length))];
      if (Math.random() < density) {
        signals.push({
          source: `student_${i}`,
          target: 'coder_agent',
          signal_type: 'feature_request',
          payload: {
            requested_by: `student_${i}`,
            feature: f,
            tier: 1 + Math.floor(Math.random() * 3),
          },
          timestamp: Date.now(),
        });
      }
    }
  }
  return JSON.stringify({ signals });
}

function runTests(): void {
  console.log('═══ Conscription Cron — Test Suite ═══\n');

  // Test 1: Empty witness log
  console.log('Test 1: Empty witness log');
  const emptyFile = '/tmp/test_empty_witness.json';
  fs.writeFileSync(emptyFile, JSON.stringify({ signals: [] }));
  const r1 = runConscriptionCron(emptyFile);
  if (r1.patches_shipped.length !== 0) {
    console.log('  ✗ FAIL: should ship 0 patches on empty log');
    process.exit(1);
  }
  console.log('  ✓ 0 patches on empty log\n');

  // Test 2: 10 students, 1 feature each — top 50%
  console.log('Test 2: 10 students, 1 feature each (sparse)');
  const sparseLog = {
    signals: Array.from({ length: 10 }, (_, i) => ({
      source: `student_${i}`,
      target: 'coder_agent',
      signal_type: 'feature_request',
      payload: { requested_by: `student_${i}`, feature: 'weather_routing', tier: 1 },
      timestamp: Date.now(),
    }))
  };
  const sparseFile = '/tmp/test_sparse_witness.json';
  fs.writeFileSync(sparseFile, JSON.stringify(sparseLog));
  const r2 = runConscriptionCron(sparseFile);
  if (r2.patches_shipped.length !== 1) {
    console.log(`  ✗ FAIL: should ship 1 patch, got ${r2.patches_shipped.length}`);
    process.exit(1);
  }
  console.log(`  ✓ Shipped ${r2.patches_shipped.length} patch from sparse log\n`);

  // Test 3: 100 students, 50 distinct features (5% quorum)
  console.log('Test 3: 100 students, 50 features (consortium)');
  const denseLog = generateTestWitnessLog(100, 12, 1.0);
  const denseFile = '/tmp/test_dense_witness.json';
  fs.writeFileSync(denseFile, denseLog);
  const r3 = runConscriptionCron(denseFile);
  if (r3.patches_shipped.length === 0) {
    console.log('  ✗ FAIL: should ship some patches from dense log');
    process.exit(1);
  }
  console.log(`  ✓ Shipped ${r3.patches_shipped.length} patches from dense log\n`);

  // Test 4: Idempotency — running twice produces same patches
  console.log('Test 4: Idempotency (run twice, same result)');
  const r4a = runConscriptionCron(denseFile);
  const r4b = runConscriptionCron(denseFile);
  const featuresA = r4a.patches_shipped.map(p => p.feature).sort();
  const featuresB = r4b.patches_shipped.map(p => p.feature).sort();
  if (JSON.stringify(featuresA) !== JSON.stringify(featuresB)) {
    console.log('  ✗ FAIL: idempotency broken');
    console.log('  Run A:', featuresA);
    console.log('  Run B:', featuresB);
    process.exit(1);
  }
  console.log(`  ✓ Idempotent — both runs shipped same ${featuresA.length} features\n`);

  // Test 5: Conflicting votes — only majority ships
  console.log('Test 5: Conflicting votes — only majority ships');
  const conflictLog = {
    signals: [
      // 8 vote yes, 2 vote no
      ...Array.from({ length: 8 }, (_, i) => ({
        source: `student_${i}`, target: 'coder_agent', signal_type: 'feature_request',
        payload: { requested_by: `student_${i}`, feature: 'maj_feature', tier: 1 },
        timestamp: Date.now(),
      })),
      ...Array.from({ length: 2 }, (_, i) => ({
        source: `student_${10+i}`, target: 'coder_agent', signal_type: 'contest',
        payload: { requested_by: `student_${10+i}`, target_feature: 'maj_feature', vote: 'no' },
        timestamp: Date.now(),
      })),
    ]
  };
  const conflictFile = '/tmp/test_conflict_witness.json';
  fs.writeFileSync(conflictFile, JSON.stringify(conflictLog));
  const r5 = runConscriptionCron(conflictFile);
  // 8/10 = 80% > 5% so maj_feature should ship
  if (r5.patches_shipped.length === 0) {
    console.log('  ✗ FAIL: should ship maj_feature');
    process.exit(1);
  }
  console.log(`  ✓ Shipped ${r5.patches_shipped[0].feature} despite 2/10 contest votes\n`);

  console.log('═══════════════════════════════════════════════════════════════════');
  console.log('  ✓ All 5 tests PASS');
  console.log('═══════════════════════════════════════════════════════════════════');
  
  // Write run log
  const runLogPath = path.join('/workspace/research/cargo-line-tycoon/cron/runs', `run_${Date.now()}.json`);
  fs.mkdirSync(path.dirname(runLogPath), { recursive: true });
  fs.writeFileSync(runLogPath, JSON.stringify(r3, null, 2));
  console.log(`\nRun log saved to: ${runLogPath}`);
}

// ─────────────────────────────────────────────────────────────────
// Main
// ─────────────────────────────────────────────────────────────────

const args = process.argv.slice(2);

if (args.length === 0 || args[0] === '--help' || args[0] === '-h') {
  console.log('Usage:');
  console.log('  npx tsx conscription_cron.ts <witness_log.json>');
  console.log('  npx tsx conscription_cron.ts --test');
  process.exit(0);
}

if (args[0] === '--test') {
  runTests();
} else {
  const witnessLogFile = args[0];
  if (!fs.existsSync(witnessLogFile)) {
    console.error(`Witness log file not found: ${witnessLogFile}`);
    process.exit(1);
  }
  const runLog = runConscriptionCron(witnessLogFile);
  const runLogPath = path.join('/workspace/research/cargo-line-tycoon/cron/runs', `run_${Date.now()}.json`);
  fs.mkdirSync(path.dirname(runLogPath), { recursive: true });
  fs.writeFileSync(runLogPath, JSON.stringify(runLog, null, 2));
  console.log(`\nRun log saved to: ${runLogPath}`);
}

